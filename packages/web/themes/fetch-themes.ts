import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const THEMES_DIR = "themes";
const OUT_FILE = "src/lib/themes.ts";

const SOURCE =
  "https://raw.githubusercontent.com/folke/tokyonight.nvim/main/extras/windows_terminal";

const THEMES: Array<{ key: "dark" | "light"; file: string }> = [
  { key: "dark", file: "tokyonight_moon.json" },
  { key: "light", file: "tokyonight_day.json" },
];

// Windows Terminal color-scheme keys -> xterm ITheme keys. Any key without a map here is dropped.
const KEY_MAP: Record<string, string> = {
  background: "background",
  foreground: "foreground",
  cursorColor: "cursor",
  selectionBackground: "selectionBackground",
  black: "black",
  red: "red",
  green: "green",
  yellow: "yellow",
  blue: "blue",
  purple: "magenta",
  cyan: "cyan",
  white: "white",
  brightBlack: "brightBlack",
  brightRed: "brightRed",
  brightGreen: "brightGreen",
  brightYellow: "brightYellow",
  brightBlue: "brightBlue",
  brightPurple: "brightMagenta",
  brightCyan: "brightCyan",
  brightWhite: "brightWhite",
};

type RawScheme = Record<string, string>;

function toITheme(raw: RawScheme) {
  const theme: Record<string, string> = {};
  for (const [key, value] of Object.entries(raw)) {
    const mapped = KEY_MAP[key];
    if (mapped) theme[mapped] = value;
  }
  return theme;
}

function indent(text: string, width: number) {
  const pad = " ".repeat(width);
  return text
    .split("\n")
    .map((line) => (line ? pad + line : line))
    .join("\n");
}

async function fetchRaw(file: string) {
  const res = await fetch(`${SOURCE}/${file}`);
  if (!res.ok) throw new Error(`Failed to fetch ${file}: ${res.status}`);
  const text = await res.text(); // Windows Terminal JSONs are prefixed by a comment block.
  return JSON.parse(text.slice(text.indexOf("{")));
}

await mkdir(THEMES_DIR, { recursive: true });

const out: Array<string> = [
  "// AUTO-GENERATED by scripts/themes/fetch-themes.ts. Do not edit.",
  "// Run `bun run themes` to refresh from the tokyonight repo.",
  "",
  'import type { ITheme } from "@xterm/xterm";',
  "",
  "export const terminalThemes: Record<'dark' | 'light', ITheme> = {",
];

for (const { key, file } of THEMES) {
  const raw = (await fetchRaw(file)) as RawScheme;
  await writeFile(join(THEMES_DIR, file), `${JSON.stringify(raw, null, 2)}\n`);
  out.push(`  ${key}: ${indent(JSON.stringify(toITheme(raw), null, 2), 4)},`);
}

out.push("};", "");
await writeFile(OUT_FILE, out.join("\n"));
console.log(`Wrote ${THEMES.length} themes to ${OUT_FILE}`);
